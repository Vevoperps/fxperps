# Rewrites backend/contracts/.env and backend/keeper/.env for Robinhood Chain
# mainnet (chain 4663), carrying the existing secrets across untouched.
#
# Nothing in this file is a secret: the keys are read out of the .env files
# already on disk and written straight back, never typed and never printed.
# The old files are copied to .env.bak first.
#
# Run from anywhere:
#   powershell -ExecutionPolicy Bypass -File D:\dev\fxperps\backend\setup-env.ps1

$ErrorActionPreference = "Stop"

$backend   = Split-Path -Parent $MyInvocation.MyCommand.Path
$contracts = Join-Path $backend "contracts\.env"
$keeper    = Join-Path $backend "keeper\.env"

# A .env value, or "" when the file or the key is absent. Split on the FIRST
# "=" only: a base64 API key can contain one.
function Get-EnvValue([string]$Path, [string]$Name) {
    if (-not (Test-Path $Path)) { return "" }
    $line = Get-Content $Path | Where-Object { $_ -match "^$Name=" } | Select-Object -First 1
    if (-not $line) { return "" }
    return ($line -split "=", 2)[1].Trim()
}

# UTF-8 with no BOM. With one, three invisible bytes land in front of the first
# variable name and the parser never sees it.
function Write-EnvFile([string]$Path, [string]$Content) {
    $dir = Split-Path -Parent $Path
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
    if (Test-Path $Path) { Copy-Item $Path "$Path.bak" -Force }
    [System.IO.File]::WriteAllText($Path, $Content, (New-Object System.Text.UTF8Encoding $false))
}

