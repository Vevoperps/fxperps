# Report by length, never by value.
function Show-Secret([string]$Path, [string]$Name) {
    $value = Get-EnvValue $Path $Name
    $state = if ($value) { "$($value.Length) chars" } else { "EMPTY" }
    Write-Host ("  {0,-18} {1}" -f $Name, $state)
}

